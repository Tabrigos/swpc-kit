"""The bundled agent skill is current, accurate, and installable.

``SKILL.md`` is written by hand, ``references/api.md`` is generated by
``tools/build_skill.py``. These tests fail when either falls behind the code:
a stale reference, a version that is not the package's, a product missing
from the table, a name that does not exist, an example that does not run.
"""

import dataclasses
import inspect
import re
import shutil
from datetime import UTC, datetime
from functools import partial
from pathlib import Path
from typing import Any

import build_skill
import pytest

import swpc_kit
import swpc_kit.client
import swpc_kit.codes
import swpc_kit.errors
import swpc_kit.export
import swpc_kit.models
import swpc_kit.parse
from swpc_kit.client import PRODUCTS, AsyncClient, Client
from swpc_kit.skill import (
    DEFAULT_TARGET,
    SKILL_NAME,
    bundled,
    check,
    install,
    main,
    read_skill,
    skill_info,
)

FIXTURES = Path(__file__).parent / "fixtures"
SKILL = read_skill()
FRONTMATTER, BODY = SKILL.split("\n---\n", 1)
FENCE = re.compile(r"^```(\w*)\n(.*?)^```$", re.MULTILINE | re.DOTALL)
PROSE = FENCE.sub("", BODY)
INLINE = re.compile(r"`([^`\n]+)`")


def _blocks(kind: str) -> list[str]:
    return [body for k, body in FENCE.findall(BODY) if k == kind]


def _public_names() -> set[str]:
    """Every attribute, field, method and module name a reader could use."""
    classes: list[Any] = [Client, AsyncClient]
    for module in (swpc_kit, swpc_kit.models, swpc_kit.errors, swpc_kit.codes):
        classes += [v for v in vars(module).values() if inspect.isclass(v)]
    names = {cls.__name__ for cls in classes}
    names |= {name for cls in classes for name in dir(cls)}
    for cls in classes:
        if dataclasses.is_dataclass(cls):
            names |= {f.name for f in dataclasses.fields(cls)}
        if dataclasses.is_dataclass(cls) or cls in (Client, AsyncClient):
            names |= set(inspect.signature(cls).parameters)
        for _, method in inspect.getmembers(cls, inspect.isfunction):
            names |= set(inspect.signature(method).parameters)
    for module in (swpc_kit.parse, swpc_kit.export, swpc_kit.codes):
        names |= set(dir(module))
    return names | {"skill", "geotiff", "write_geotiff", "export", "parse", "client"}


# --- frontmatter --------------------------------------------------------------


def test_frontmatter_follows_the_agent_skills_format() -> None:
    assert FRONTMATTER.startswith("---\n")
    info = skill_info(SKILL)
    assert info.name == SKILL_NAME == bundled().name
    assert re.fullmatch(r"[a-z0-9-]{1,64}", SKILL_NAME)
    description = re.search(r"^description: >-\n((?:  .*\n?)+)", FRONTMATTER, re.M)
    assert description is not None
    text = " ".join(line.strip() for line in description[1].splitlines())
    assert 0 < len(text) <= 1024
    assert "<" not in text
    assert ">" not in text


def test_version_is_the_package_version() -> None:
    assert skill_info(SKILL).version == swpc_kit.__version__


def test_skill_stays_short() -> None:
    assert len(SKILL.splitlines()) <= 500


# --- the generated reference -------------------------------------------------


def test_api_reference_is_current() -> None:
    committed = bundled().joinpath("references", "api.md").read_text("utf-8")
    assert committed == build_skill.build(), (
        "references/api.md is stale: run `uv run python tools/build_skill.py`"
    )


def test_api_reference_covers_every_product_and_model() -> None:
    reference = build_skill.build()
    for product in PRODUCTS:
        assert f"`{product.name}`" in reference
    for name in swpc_kit.models.__all__:
        assert f"### `{name}" in reference, name


def test_referenced_files_exist() -> None:
    for path in set(re.findall(r"`(references/[\w./-]+)`", BODY)):
        assert bundled().joinpath(*path.split("/")).is_file(), path


# --- the hand-written guide matches the code ---------------------------------


def test_product_table_lists_every_client_method() -> None:
    rows = re.findall(r"^\| [^|]+ \| `(\w+)` \|", BODY, re.MULTILINE)
    assert sorted(rows) == sorted(p.name for p in PRODUCTS)
    for name in rows:
        assert callable(getattr(Client, name))
        assert inspect.iscoroutinefunction(getattr(AsyncClient, name))


def test_parsers_named_exist() -> None:
    names = set(re.findall(r"\bparse_\w+", BODY))
    assert names
    assert names <= set(swpc_kit.parse.__all__), names - set(swpc_kit.parse.__all__)


def test_dotted_paths_resolve() -> None:
    for path in set(re.findall(r"\bswpc_kit(?:\.\w+)+", PROSE)):
        module, _, attr = path.rpartition(".")
        try:
            target = __import__(path, fromlist=["_"])
        except ImportError:
            target = getattr(__import__(module, fromlist=["_"]), attr)
        assert target is not None, path


def test_names_in_inline_code_exist() -> None:
    known = _public_names()
    unknown: set[str] = set()
    for span in INLINE.findall(PROSE):
        if "/" in span or " " in span.split("(")[0].strip():
            continue  # paths and shell commands
        if re.search(r"\.(json|txt|md)$", span) or span == "metadata.version":
            continue  # file names, the frontmatter
        words = re.findall(r"\.([A-Za-z_]\w*)|([A-Za-z_]\w*)\(|([A-Za-z_]\w*)=", span)
        for groups in words:
            word = next(g for g in groups if g)
            if word not in known:
                unknown.add(f"{word} (in `{span}`)")
    assert not unknown, sorted(unknown)


def test_table_attributes_exist() -> None:
    known = _public_names()
    for row in re.findall(r"^\| .+ \| `\w+` \| (.+) \|$", BODY, re.MULTILINE):
        for span in INLINE.findall(row):
            if "/" in span:
                continue
            for word in re.findall(r"[A-Za-z_]\w*", re.sub(r'"[^"]*"', "", span)):
                assert word in known, (word, row)


# --- the examples run --------------------------------------------------------


@pytest.fixture
def workdir(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, swpc_from_fixtures: None
) -> Path:
    shutil.copy(FIXTURES / "dst" / "2026-10-15.json", tmp_path / "kyoto-dst.json")
    monkeypatch.chdir(tmp_path)
    return tmp_path


def test_python_examples_run(
    workdir: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    # The fixtures were recorded on 2026-10-15: run the examples as if then.
    then = datetime(2026, 10, 15, 13, tzinfo=UTC)
    monkeypatch.setattr(swpc_kit.client, "Client", partial(Client, clock=lambda: then))
    blocks = _blocks("python")
    assert len(blocks) >= 3
    namespace: dict[str, Any] = {"__name__": "skill"}
    for number, code in enumerate(blocks):
        exec(compile(code, f"SKILL.md python block {number}", "exec"), namespace)
    raw = (FIXTURES / "ovation-aurora" / "2026-10-15.json").read_bytes()
    oval = swpc_kit.parse.parse_ovation_aurora(raw, partial=True)
    assert namespace["aurora_geojson"](oval)["type"] == "FeatureCollection"
    printed = capsys.readouterr().out
    assert printed.startswith("2026-10-15 12:00:00+00:00 2.67\n"), printed


def test_shell_commands_name_real_subcommands() -> None:
    for line in "".join(_blocks("bash")).splitlines():
        if "swpc_kit.skill" in line:
            command = line.split("#")[0].split()[3:]
            with pytest.raises(SystemExit) as exit_:
                main([*command, "--help"])
            assert exit_.value.code == 0


# --- the command line ---------------------------------------------------------


def test_install_copies_the_whole_skill(tmp_path: Path) -> None:
    target = tmp_path / "skills" / SKILL_NAME
    assert install(target) == target
    assert (target / "SKILL.md").read_text("utf-8") == SKILL
    reference = bundled().joinpath("references", "api.md").read_text("utf-8")
    assert (target / "references" / "api.md").read_text("utf-8") == reference
    assert not list(target.rglob("*.py*"))


def test_check_reports_missing_outdated_and_current(tmp_path: Path) -> None:
    target = tmp_path / SKILL_NAME
    missing = check(target)
    assert not missing.current
    assert missing.installed is None

    install(target)
    status = check(target)
    assert status.current
    assert status.installed == swpc_kit.__version__

    old = SKILL.replace(f'version: "{swpc_kit.__version__}"', 'version: "0.0.1"')
    (target / "SKILL.md").write_text(old, encoding="utf-8")
    outdated = check(target)
    assert not outdated.current
    assert outdated.installed == "0.0.1"
    assert "install" in outdated.message


def test_install_replaces_an_older_copy(tmp_path: Path) -> None:
    target = tmp_path / SKILL_NAME
    install(target)
    (target / "stale.md").write_text("old", encoding="utf-8")
    install(target)
    assert not (target / "stale.md").exists()


def test_install_leaves_other_directories_alone(tmp_path: Path) -> None:
    target = tmp_path / "mine"
    target.mkdir()
    (target / "notes.md").write_text("keep", encoding="utf-8")
    with pytest.raises(FileExistsError):
        install(target)
    assert (target / "notes.md").read_text("utf-8") == "keep"
    install(target, force=True)
    assert not (target / "notes.md").exists()
    assert check(target).current


def test_command_line(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.chdir(tmp_path)
    assert main(["check"]) == 1
    assert "not installed" in capsys.readouterr().out
    assert main(["install"]) == 0
    assert (tmp_path / DEFAULT_TARGET / "SKILL.md").is_file()
    assert swpc_kit.__version__ in capsys.readouterr().out
    assert main(["check"]) == 0
    assert "current" in capsys.readouterr().out

    other = tmp_path / "other"
    other.mkdir()
    (other / "x").write_text("x", encoding="utf-8")
    assert main(["install", "--target", str(other)]) == 1
    assert "--force" in capsys.readouterr().err
    assert main(["install", "--target", str(other), "--force"]) == 0
    capsys.readouterr()

    assert main(["show"]) == 0
    assert capsys.readouterr().out == SKILL
    assert main(["path"]) == 0
    assert capsys.readouterr().out.strip().endswith(SKILL_NAME)
